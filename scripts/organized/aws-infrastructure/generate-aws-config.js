#!/usr/bin/env node

/**
 * AWS Resources Configuration Generator
 * Generates config/aws-resources.js from environment variables
 */

require('dotenv').config();
const fs = require('fs');
const path = require('path');

console.log('🔧 AWS Resources Configuration Generator');
console.log('━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━');

// Check if we have the necessary env vars
const requiredVars = [
  'APPRUNNER_SERVICE_ARN',
  'AWS_ACCOUNT_ID',
  'AWS_REGION'
];

const missingVars = requiredVars.filter(v => !process.env[v]);

if (missingVars.length > 0) {
  console.log('');
  console.log('❌ Missing required environment variables:');
  missingVars.forEach(v => console.log(`   - ${v}`));
  console.log('');
  console.log('📝 Please add these to your .env file:');
  console.log('');
  console.log('   # AWS Configuration');
  console.log('   AWS_ACCOUNT_ID=your-account-id');
  console.log('   AWS_REGION=us-east-1');
  console.log('   APPRUNNER_SERVICE_ARN=arn:aws:apprunner:us-east-1:ACCOUNT_ID:service/SERVICE_NAME/SERVICE_ID');
  console.log('');
  console.log('💡 You can find these in the AWS Console:');
  console.log('   - AWS Account ID: Click your name in top-right → Account');
  console.log('   - App Runner ARN: App Runner → Your Service → Configuration');
  console.log('');
  process.exit(1);
}

// Generate the config file content
const configContent = `/**
 * AWS Resource Configuration
 * AUTO-GENERATED from environment variables
 * Do not edit this file directly - update .env instead and regenerate
 */

module.exports = {
  // AWS Account Information
  aws: {
    accountId: process.env.AWS_ACCOUNT_ID || '${process.env.AWS_ACCOUNT_ID}',
    region: process.env.AWS_REGION || '${process.env.AWS_REGION}'
  },

  // App Runner Service
  appRunner: {
    serviceArn: process.env.APPRUNNER_SERVICE_ARN || 
      '${process.env.APPRUNNER_SERVICE_ARN}',
    serviceName: process.env.APPRUNNER_SERVICE_NAME || '${process.env.APPRUNNER_SERVICE_NAME || 'wavelength-lore'}',
    serviceId: process.env.APPRUNNER_SERVICE_ID || '${process.env.APPRUNNER_SERVICE_ID || ''}'
  },

  // S3 Resources
  s3: {
    bucketName: process.env.S3_BUCKET_NAME || '${process.env.S3_BUCKET_NAME || 'wavelength-lore-static'}',
    backupBucketName: process.env.BACKUP_S3_BUCKET || '${process.env.BACKUP_S3_BUCKET || 'wavelength-lore-backups'}'
  },

  // CloudFront
  cloudFront: {
    distributionId: process.env.CLOUDFRONT_DISTRIBUTION_ID || '${process.env.CLOUDFRONT_DISTRIBUTION_ID || ''}',
    distributionDomain: process.env.CDN_URL ? process.env.CDN_URL.replace('https://', '') : '${(process.env.CDN_URL || '').replace('https://', '')}',
    etag: process.env.CLOUDFRONT_ETAG || ''
  },

  // ECR Repository
  ecr: {
    repositoryUri: process.env.ECR_REPOSITORY_URI || 
      '${process.env.ECR_REPOSITORY_URI || ''}'
  }
};
`;

// Write the config file
const configPath = path.join(process.cwd(), 'config', 'aws-resources.js');

try {
  fs.writeFileSync(configPath, configContent, 'utf8');
  console.log('');
  console.log('✅ Successfully generated config/aws-resources.js');
  console.log('');
  console.log('📋 Configuration:');
  console.log(`   AWS Account: ${process.env.AWS_ACCOUNT_ID}`);
  console.log(`   AWS Region: ${process.env.AWS_REGION}`);
  console.log(`   App Runner ARN: ${process.env.APPRUNNER_SERVICE_ARN}`);
  console.log('');
  console.log('✅ You can now run:');
  console.log('   node scripts/apprunner-env-updater.js');
  console.log('');
} catch (error) {
  console.error('❌ Error writing config file:', error.message);
  process.exit(1);
}
